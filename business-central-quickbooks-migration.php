    (function () {
        if (!('IntersectionObserver' in window) ||
            window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
            return;
        }
        var targets = document.querySelectorAll('.qbm-reveal, .qbm-stagger');
        document.documentElement.classList.add('qbm-anim');
        var observer = new IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (!entry.isIntersecting) return;
                var el = entry.target;
                el.classList.add('qbm-visible');
                if (el.classList.contains('qbm-stagger')) {
                    // hand the cards back to their own hover styles once they are in
                    setTimeout(function () { el.classList.remove('qbm-stagger', 'qbm-visible'); }, 1400);
                }
                observer.unobserve(el);
            });
        }, { threshold: 0.15 });
        targets.forEach(function (el) { observer.observe(el); });
    })();
