<!-- ================= History & Evolution ================= -->
<section class="erp-section bg-light">
  <h2 class="erp-section-title">History & Evolution</h2>
  <p class="erp-section-text">
    ERP began over a century ago as paper-based production scheduling. By the 1960s, manufacturers adopted
    computerized systems, leading to standalone solutions like MRP. In the 1990s, ERP expanded across industries,
    and with cloud technology, it became more accessible. Today, AI and machine learning enhance ERP, driving
    efficiency and real-time insights.
  </p>
</section>

