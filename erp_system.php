<!-- ================= How ERP Systems Work ================= -->
<section class="erp-section bg-light">
  <h2 class="erp-section-title">How do ERP Systems Work?</h2>
  <p class="erp-section-text">
    An ERP system consists of integrated modules that share a common database, enabling seamless communication
    across departments. Each module focuses on specific business areas like finance, logistics, procurement, or HR,
    allowing companies to customize and scale as needed.
  </p>
  <p class="erp-section-text">
    Modern ERP systems integrate with CRM, HCM, e-commerce, and industry-specific solutions, providing a unified
    view of data for improved efficiency and collaboration. They connect via APIs, Enterprise Service Bus (ESB), or
    Integration Platform-as-a-service (iPaaS), ensuring flexibility and synchronization across various software
    applications.
  </p>
</section>

<!-- ================= Types of ERP Deployment ================= -->
<section class="erp-section">
  <h2 class="erp-section-title">Types of ERP Deployment</h2>
  <h3 class="erp-subtitle">On-Premise ERP</h3>
  <p>Installed in a company’s data center, on-premise ERP offers full control but requires handling installation, updates, and maintenance.</p>
  
  <h3 class="erp-subtitle">Cloud ERP</h3>
  <p>Hosted on a third-party server, accessed via subscription. Provider manages maintenance, updates, and security.</p>

  <h3 class="erp-subtitle">Two-Tier ERP</h3>
  <p>Combines Tier 1 on-premise for HQ and Tier 2 cloud-based for subsidiaries. Ideal for gradual cloud transition.</p>

  <h3 class="erp-subtitle">Hybrid ERP</h3>
  <p>Blends on-premise and cloud. Flexible, supports compliance, and eases transition toward full cloud adoption.</p>
</section>

